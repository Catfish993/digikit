//! Generators for the typed module sections (`typed.rs`): from one `module.toml`, per module,
//!
//! - `build/gen/consts.rs`: Rust constants for SDK users (`include!` it in a module crate): per device the frame
//!   layout, the machine type numbers and, per parameter, its knob, slot, frame offset, mirror index and range;
//! - `build/gen/<device>.inc`: the same numbers as `#define`s for SHARC assembly (`#include "<device>.inc"`);
//! - `build/gen/gallery.json`: machines with their knobs and parameters, per device, for the gallery.
//!
//! The outputs are committed; `patchkit gen --check` fails when a committed file differs from a fresh one. They carry
//! no firmware bytes: only the numbers the module itself declares and the device models.

use crate::error::*;
use crate::module::Library;
use crate::typed::{DevResolved, Knob, Models, RMachine, resolve};
use std::fmt::Write;

/// One generated file: path relative to the module directory, and its text.
pub type GenFile = (String, String);

fn upper(id: &str) -> String {
    id.to_ascii_uppercase()
}

/// The permanent type number of a machine (`core/machines` types.toml), if the framework is in the library.
fn type_number(lib: &Library, dev: &str, module: &str, machine: &str) -> Option<i64> {
    let d = lib
        .get("core/machines")?
        .alloc
        .get("machines")?
        .devices
        .get(dev)?;
    let key = format!("{module}:{machine}");
    d.alloc.get(&key).copied()
}

fn hex(v: i64) -> String {
    if v < 0 {
        v.to_string()
    } else {
        format!("{v:#x}")
    }
}

/// Knob offsets of a machine: (knob position, frame offset) for every non-empty knob.
fn knob_offsets(r: &DevResolved, m: &RMachine) -> Vec<(usize, i64)> {
    m.knobs
        .iter()
        .enumerate()
        .filter(|(_, k)| !matches!(k, Knob::Code(0)))
        .map(|(j, _)| (j, r.model.frame_offset(j)))
        .collect()
}

/// Lines `(NAME, value, comment)` of one device, shared by the Rust and SHARC outputs.
fn constants(lib: &Library, module: &str, r: &DevResolved) -> Vec<(String, i64, String)> {
    let mut v: Vec<(String, i64, String)> = vec![];
    let mut add = |n: String, x: i64, c: &str| v.push((n, x, c.to_string()));
    let f = &r.model.frame;
    add(
        "FRAME_BASE".into(),
        f.base,
        "halfword index of knob 0 of track (voice) 0 in the DSP's frame copy",
    );
    add(
        "FRAME_STRIDE".into(),
        f.stride,
        "halfwords from one track (voice) to the next",
    );
    add(
        "SLOT_BASE".into(),
        r.model.knobs.slot_base,
        "slot of knob 0",
    );
    add(
        "KNOBS".into(),
        r.model.knobs.count as i64,
        "knobs per machine",
    );
    for m in &r.machines {
        let p = upper(&m.id);
        if let Some(t) = type_number(lib, &r.dev, module, &m.id) {
            add(format!("{p}_TYPE"), t, "permanent machine type number");
        }
        for (j, off) in knob_offsets(r, m) {
            add(format!("{p}_KNOB{j}_FRAME_OFF"), off, "");
        }
    }
    for q in &r.params {
        let p = upper(&q.id);
        add(format!("{p}_KNOB"), q.knob as i64, "knob position");
        add(format!("{p}_SLOT"), q.slot, "engine or sound-array slot");
        add(
            format!("{p}_FRAME_OFF"),
            q.frame_off,
            "halfwords from knob 0 of the same track",
        );
        add(
            format!("{p}_MIRROR"),
            q.mirror,
            "index in the parameter table",
        );
        add(format!("{p}_MIN"), q.min, "");
        add(format!("{p}_MAX"), q.max, "");
        add(format!("{p}_DEFAULT"), q.default, "");
    }
    v
}

const NOTE: &str = "generated by `patchkit gen` from module.toml; do not edit";

fn rust(lib: &Library, module: &str, rs: &[DevResolved]) -> String {
    let mut s =
        format!("// {module}: {NOTE}.\n// Use: `include!(\"consts.rs\");` in a module crate.\n\n");
    for r in rs {
        let _ = writeln!(s, "pub mod {} {{", r.dev);
        for (n, x, c) in constants(lib, module, r) {
            let _ = write!(s, "    pub const {n}: u32 = {};", hex(x));
            if !c.is_empty() {
                let _ = write!(s, " // {c}");
            }
            s.push('\n');
        }
        s.push_str(
            "\n    /// Halfword index in the DSP's frame copy of the word at `offset` of `track` (voice).\n    pub const fn frame_halfword(track: u32, offset: u32) -> u32 {\n        FRAME_BASE + FRAME_STRIDE * track + offset\n    }\n}\n\n",
        );
    }
    s.truncate(s.trim_end().len());
    s.push('\n');
    s
}

fn sharc(lib: &Library, module: &str, r: &DevResolved) -> String {
    let mut s = format!(
        "// {module} on {}: {NOTE}.\n// Decimal values: the assembler upper-cases macro text, which breaks `0x` literals after `+`.\n// Use: `#include \"{}.inc\"`. A knob word of track t is halfword FRAME_BASE + FRAME_STRIDE * t + <NAME>_FRAME_OFF.\n",
        r.dev, r.dev
    );
    for (n, x, c) in constants(lib, module, r) {
        let _ = write!(s, "#define {n} {x}");
        if !c.is_empty() {
            let _ = write!(s, " // {c}");
        }
        s.push('\n');
    }
    s
}

fn gallery(lib: &Library, module: &str, rs: &[DevResolved]) -> Result<String> {
    use serde_json::{Map, Value, json};
    let mut machines: Vec<Value> = vec![];
    let mut ids: Vec<String> = vec![];
    for r in rs {
        for m in &r.machines {
            if !ids.contains(&m.id) {
                ids.push(m.id.clone());
            }
        }
    }
    for id in &ids {
        let mut devs = Map::new();
        let mut first: Option<&RMachine> = None;
        for r in rs {
            let Some(m) = r.machines.iter().find(|m| &m.id == id) else {
                continue;
            };
            first.get_or_insert(m);
            let knobs: Vec<Value> = m
                .knobs
                .iter()
                .enumerate()
                .map(|(j, k)| match k {
                    Knob::Code(0) => Value::Null,
                    Knob::Code(c) => {
                        json!({"slot": r.model.knobs.slot_base + j as i64, "stock": c})
                    }
                    Knob::Param(p) => {
                        json!({"slot": r.model.knobs.slot_base + j as i64, "param": p})
                    }
                })
                .collect();
            let page = r
                .pages
                .iter()
                .find(|p| &p.machine == id)
                .map(|p| json!({"name": p.name, "title": p.title}));
            devs.insert(
                r.dev.clone(),
                json!({
                    "name": m.name, "short": m.short, "type": type_number(lib, &r.dev, module, id),
                    "clone_of": m.clone_of, "position": m.position, "own_dsp": m.own_dsp,
                    "level": m.level, "knobs": knobs, "page": page,
                }),
            );
        }
        let m = first.unwrap();
        machines.push(json!({"id": id, "name": m.name, "short": m.short, "devices": devs}));
    }
    let mut params = Map::new();
    for r in rs {
        let list: Vec<Value> = r
            .params
            .iter()
            .map(|p| {
                json!({"id": p.id, "name": p.name, "short": p.short, "min": p.min, "max": p.max,
                       "default": p.default, "slot": p.slot, "template": p.template})
            })
            .collect();
        params.insert(r.dev.clone(), Value::Array(list));
    }
    Ok(serde_json::to_string_pretty(
        &json!({"module": module, "machines": machines, "params": params}),
    )? + "\n")
}

/// The generated files of one module (empty: the module has no typed sections).
pub fn generate(lib: &Library, models: &Models, module: &str) -> Result<Vec<GenFile>> {
    let m = lib
        .get(module)
        .ok_or_else(|| err!("unknown module {module}"))?;
    if !crate::typed::has_typed(&m.manifest) {
        return Ok(vec![]);
    }
    let rs = resolve(&m.manifest, models)?;
    let mut out = vec![("build/gen/consts.rs".to_string(), rust(lib, module, &rs))];
    for r in &rs {
        out.push((format!("build/gen/{}.inc", r.dev), sharc(lib, module, r)));
    }
    out.push((
        "build/gen/gallery.json".to_string(),
        gallery(lib, module, &rs)?,
    ));
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::module::Module;

    fn lib_of(text: &str) -> (Library, Models) {
        let m = Module::from_parts(text, &|_| Err(err!("no files"))).unwrap();
        let models = Models::from_texts([
            include_str!("../../../devices/digitakt-ii.toml"),
            include_str!("../../../devices/digitone-ii.toml"),
        ])
        .unwrap();
        let mut lib = Library { modules: vec![m] };
        lib.lower(&models).unwrap();
        (lib, models)
    }

    const MOD: &str = r#"
[module]
id = "machines/t"
version = "0.1.0"
name = "T"
category = "machines"
type = "machine"
author = "digikit"
status = "experimental"
summary = "t."
[[param]]
id = "t_a"
name = "A"
short = "A"
template = 0xd1
min = 0
max = 100
default = 50
[[param]]
id = "t_b"
name = "B"
short = "B"
template = 0xd1
min = 0
max = 100
default = 1
[[machine]]
id = "t"
name = "T"
short = "T"
clone_of = 0
knobs = [0xca, "t_a", 0, 0, "t_b"]
[machine.dn2]
knobs = ["t_a", "t_b"]
"#;

    #[test]
    fn constants_follow_the_device_models() {
        let (lib, models) = lib_of(MOD);
        let files = generate(&lib, &models, "machines/t").unwrap();
        let get = |n: &str| &files.iter().find(|f| f.0 == n).unwrap().1;
        let dt2 = get("build/gen/dt2.inc");
        assert!(dt2.contains("#define FRAME_BASE 109 "), "{dt2}");
        assert!(dt2.contains("#define T_B_FRAME_OFF 6 "), "{dt2}");
        assert!(dt2.contains("#define T_B_MIRROR 31 "), "{dt2}");
        let dn2 = get("build/gen/dn2.inc");
        assert!(dn2.contains("#define T_B_FRAME_OFF 1 "), "{dn2}");
        assert!(dn2.contains("#define T_B_SLOT 26 "), "{dn2}");
        let rs = get("build/gen/consts.rs");
        assert!(rs.contains("pub mod dt2 {") && rs.contains("pub mod dn2 {"));
        assert!(rs.contains("pub const T_A_SLOT: u32 = 0x1;"), "{rs}");
        let g: serde_json::Value = serde_json::from_str(get("build/gen/gallery.json")).unwrap();
        assert_eq!(
            g["machines"][0]["devices"]["dt2"]["knobs"][4]["param"],
            "t_b"
        );
        assert_eq!(g["params"]["dn2"][1]["slot"], 26);
    }

    #[test]
    fn a_module_without_typed_sections_generates_nothing() {
        let (lib, models) = lib_of(
            "[module]\nid = \"machines/t\"\nversion = \"0.1.0\"\nname = \"T\"\ncategory = \"machines\"\ntype = \"machine\"\nauthor = \"digikit\"\nstatus = \"experimental\"\nsummary = \"t.\"\n",
        );
        assert!(generate(&lib, &models, "machines/t").unwrap().is_empty());
    }
}
