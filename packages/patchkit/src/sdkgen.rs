//! The module contract (`sdk/sdk.toml`): the major version numbers and the log kinds of the digikit runtime, and the numbers of the
//! SysEx protocol. `patchkit gen` writes the Rust constants of the runtime and the Python table of `tools/device/dklog.py` from it,
//! the protocol numbers for the Python and Rust hosts, and `gen --check` keeps them current.

use crate::error::*;
use serde::Deserialize;
use std::collections::BTreeMap;
use std::fmt::Write;

/// The contract file, relative to the repository root.
pub const SOURCE: &str = "sdk/sdk.toml";
/// The generated Rust file, relative to the repository root.
pub const RUST_OUT: &str = "modules/core/runtime/sdk/src/gen_sdk.rs";
/// The generated Python file, relative to the repository root.
pub const PY_OUT: &str = "tools/device/dklog_kinds.py";
/// The generated SHARC+ include of the machine contract, relative to the repository root.
pub const INC_OUT: &str = "sdk/dk_machine.inc";
/// The generated SHARC+ include of the FX contract, relative to the repository root.
pub const FX_INC_OUT: &str = "sdk/dk_fx.inc";
/// The generated Python protocol numbers, relative to the repository root.
pub const PROTO_PY_OUT: &str = "tools/device/dkproto.py";
/// The generated Rust protocol numbers of the host client, relative to the repository root.
pub const PROTO_RS_OUT: &str = "packages/dkupload/src/gen_proto.rs";

const HEADER: &str = "Generated by `patchkit gen` from sdk/sdk.toml. Do not edit.";
const LEVELS: [&str; 5] = ["error", "warn", "info", "debug", "trace"];
const PY_WIDTH: usize = 88;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Sdk {
    runtime: Runtime,
    contract: Contract,
    machine: Machine,
    fx: Fx,
    log: Log,
    protocol: Protocol,
    load: Load,
}
/// The SysEx protocol's numbers: `[protocol]` of `sdk/sdk.toml`.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Protocol {
    version: u8,
    commands: BTreeMap<String, u8>,
    status: BTreeMap<String, Status>,
    caps: BTreeMap<String, u32>,
}
/// `[load]`: the load-result codes.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Load {
    status: BTreeMap<String, Status>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Status {
    code: i32,
    text: String,
}
/// The machine contract's numbers: `[machine]` of `sdk/sdk.toml`.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Machine {
    pub consts: Vec<MachineConst>,
    /// Field names of `struct dk_voice_in` in order (each field is 4 bytes).
    pub voice_in: Vec<String>,
    /// Field names of `struct dk_machine_desc` in order (each field is 4 bytes).
    pub desc: Vec<String>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub struct MachineConst {
    pub name: String,
    pub value: u32,
}

/// The FX contract's numbers: `[fx]` of `sdk/sdk.toml`.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Fx {
    pub consts: Vec<MachineConst>,
    /// Field names of `struct dk_fx_in` in order (each field is 4 bytes).
    pub fx_in: Vec<String>,
    /// Field names of `struct dk_fx_desc` in order (each field is 4 bytes).
    pub desc: Vec<String>,
}

/// `[fx]` of a `sdk/sdk.toml` text (for the header test).
pub fn fx(text: &str) -> Result<Fx> {
    Ok(parse(text)?.fx)
}

/// `[machine]` of a `sdk/sdk.toml` text (for the header test).
pub fn machine(text: &str) -> Result<Machine> {
    Ok(parse(text)?.machine)
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Runtime {
    version: String,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Contract {
    api: [u8; 2],
    machine: [u8; 2],
    fx: [u8; 2],
    service: [u8; 2],
}

/// The contract versions of `sdk/sdk.toml`, each (major, minor); major 0 = not implemented.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ContractVersions {
    pub api: (u8, u8),
    pub machine: (u8, u8),
    pub fx: (u8, u8),
    pub service: (u8, u8),
}

/// The contract versions of the `sdk/sdk.toml` this crate was built with (what `pack` writes into a `.dkm`).
pub fn embedded() -> ContractVersions {
    let c = parse(include_str!("../../../sdk/sdk.toml"))
        .expect("sdk/sdk.toml parses")
        .contract;
    ContractVersions {
        api: (c.api[0], c.api[1]),
        machine: (c.machine[0], c.machine[1]),
        fx: (c.fx[0], c.fx[1]),
        service: (c.service[0], c.service[1]),
    }
}

/// The runtime version of a parsed file as (major, minor, patch).
fn runtime_parts(sdk: &Sdk) -> Result<(u8, u8, u8)> {
    let s = &sdk.runtime.version;
    let p: Vec<&str> = s.split('.').collect();
    if p.len() != 3 {
        return Err(err!(
            "{SOURCE}: runtime version {s:?}: expected major.minor.patch"
        ));
    }
    let mut v = [0u8; 3];
    for (i, x) in p.iter().enumerate() {
        v[i] = x.parse().map_err(|_| {
            err!("{SOURCE}: runtime version {s:?}: each part is a number from 0 to 255")
        })?;
    }
    Ok((v[0], v[1], v[2]))
}

fn pack_runtime((a, b, c): (u8, u8, u8)) -> u32 {
    u32::from(a) << 16 | u32::from(b) << 8 | u32::from(c)
}

/// The runtime version of the `sdk/sdk.toml` this crate was built with, packed major << 16 | minor << 8 | patch.
pub fn embedded_runtime() -> u32 {
    let sdk = parse(include_str!("../../../sdk/sdk.toml")).expect("sdk/sdk.toml parses");
    pack_runtime(runtime_parts(&sdk).expect("sdk/sdk.toml runtime version"))
}

/// Read the contract versions from `sdk/sdk.toml` under the repository root.
pub fn contract(root: &std::path::Path) -> Result<ContractVersions> {
    let path = root.join(SOURCE);
    let text = std::fs::read_to_string(&path).map_err(|e| err!("{}: {e}", path.display()))?;
    let c = parse(&text)?.contract;
    Ok(ContractVersions {
        api: (c.api[0], c.api[1]),
        machine: (c.machine[0], c.machine[1]),
        fx: (c.fx[0], c.fx[1]),
        service: (c.service[0], c.service[1]),
    })
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Log {
    f_error: u16,
    level_shift: u16,
    level_mask: u16,
    source_shift: u16,
    source_mask: u16,
    #[serde(default)]
    consts: BTreeMap<String, u32>,
    #[serde(default)]
    guard_kinds: BTreeMap<String, String>,
    kind: Vec<Kind>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Kind {
    id: u16,
    name: String,
    args: Vec<String>,
}

fn parse(text: &str) -> Result<Sdk> {
    let sdk: Sdk = toml::from_str(text).map_err(|e| err!("{SOURCE}: {e}"))?;
    let mut last = 0;
    for k in &sdk.log.kind {
        if k.id <= last {
            return Err(err!(
                "{SOURCE}: kind {} ({}) is not in ascending order",
                k.id,
                k.name
            ));
        }
        last = k.id;
        if k.args.len() != 5 {
            return Err(err!("{SOURCE}: kind {} ({}) needs 5 args", k.id, k.name));
        }
    }
    for (i, k) in sdk.log.kind.iter().enumerate() {
        if sdk.log.kind[..i].iter().any(|o| o.name == k.name) {
            return Err(err!("{SOURCE}: kind name {} twice", k.name));
        }
    }
    runtime_parts(&sdk)?;
    let p = &sdk.protocol;
    for (i, (n, v)) in p.commands.iter().enumerate() {
        if p.commands.iter().skip(i + 1).any(|(_, w)| w == v) {
            return Err(err!("{SOURCE}: protocol command number {v:#04x} ({n}) twice"));
        }
    }
    for (i, (n, v)) in p.caps.iter().enumerate() {
        if *v > 31 {
            return Err(err!("{SOURCE}: protocol cap {n}: bit {v} is not below 32"));
        }
        if p.caps.iter().skip(i + 1).any(|(_, w)| w == v) {
            return Err(err!("{SOURCE}: protocol cap bit {v} ({n}) twice"));
        }
    }
    for (what, table) in [("protocol", &p.status), ("load", &sdk.load.status)] {
        for (i, (n, s)) in table.iter().enumerate() {
            if s.code >= 0 || (what == "protocol" && s.code < -128) {
                return Err(err!("{SOURCE}: {what} status {n}: code {} out of range", s.code));
            }
            if table.iter().skip(i + 1).any(|(_, t)| t.code == s.code) {
                return Err(err!("{SOURCE}: {what} status code {} ({n}) twice", s.code));
            }
        }
    }
    Ok(sdk)
}

/// The statuses in the order of their codes, from -1 down.
fn by_code(t: &BTreeMap<String, Status>) -> Vec<(&String, &Status)> {
    let mut v: Vec<_> = t.iter().collect();
    v.sort_by_key(|(_, s)| -s.code);
    v
}

/// The (name, value) pairs of a table in value order.
fn by_value<T: Ord + Copy>(t: &BTreeMap<String, T>) -> Vec<(&String, T)> {
    let mut v: Vec<_> = t.iter().map(|(n, x)| (n, *x)).collect();
    v.sort_by_key(|(_, x)| *x);
    v
}

/// The protocol's Rust constants, one per line with `indent`; the statuses have type `status_ty`.
fn proto_consts(sdk: &Sdk, indent: &str, status_ty: &str) -> String {
    let p = &sdk.protocol;
    let mut s = String::new();
    let _ = writeln!(s, "{indent}pub const VERSION: u8 = {};", p.version);
    for (n, v) in by_value(&p.commands) {
        let _ = writeln!(s, "{indent}pub const CMD_{n}: u8 = {v:#04x};");
    }
    for (n, st) in by_code(&p.status) {
        let _ = writeln!(s, "{indent}pub const {n}: {status_ty} = {};", st.code);
    }
    for (n, bit) in by_value(&p.caps) {
        let _ = writeln!(s, "{indent}pub const CAP_{n}: u32 = 1 << {bit};");
    }
    s
}

fn guards(sdk: &Sdk) -> Result<Vec<(u32, &str)>> {
    let mut v = Vec::new();
    for (k, name) in &sdk.log.guard_kinds {
        let id: u32 = k
            .parse()
            .map_err(|_| err!("{SOURCE}: guard_kinds key {k} is not a number"))?;
        v.push((id, name.as_str()));
    }
    v.sort();
    Ok(v)
}

fn rust(sdk: &Sdk) -> String {
    let mut s = format!("// {HEADER}\n\n");
    let rv = runtime_parts(sdk).expect("parse checked the runtime version");
    let _ = writeln!(s, "// {}.{}.{}", rv.0, rv.1, rv.2);
    let _ = writeln!(
        s,
        "pub const RUNTIME_VERSION: u32 = {:#08x};\n",
        pack_runtime(rv)
    );
    let c = &sdk.contract;
    s.push_str("pub mod contract {\n");
    for (n, v) in [
        ("API", c.api),
        ("MACHINE", c.machine),
        ("FX", c.fx),
        ("SERVICE", c.service),
    ] {
        let _ = writeln!(s, "    pub const {n}: (u8, u8) = ({}, {});", v[0], v[1]);
    }
    s.push_str("}\n\npub mod logk {\n");
    for k in &sdk.log.kind {
        let _ = writeln!(s, "    pub const {}: u16 = {};", k.name, k.id);
    }
    let mut consts: Vec<(&String, &u32)> = sdk.log.consts.iter().collect();
    consts.sort_by_key(|(n, v)| (**v, (*n).clone()));
    for (n, v) in consts {
        let _ = writeln!(s, "    pub const {n}: u32 = {v};");
    }
    let l = &sdk.log;
    for (n, v) in [
        ("F_ERROR", l.f_error),
        ("LEVEL_SHIFT", l.level_shift),
        ("LEVEL_MASK", l.level_mask),
        ("SOURCE_SHIFT", l.source_shift),
        ("SOURCE_MASK", l.source_mask),
    ] {
        let _ = writeln!(s, "    pub const {n}: u16 = {v};");
    }
    for (i, n) in LEVELS.iter().enumerate() {
        let _ = writeln!(s, "    pub const L_{}: u16 = {i};", n.to_uppercase());
    }
    s.push_str("}\n\npub mod proto {\n");
    s.push_str(&proto_consts(sdk, "    ", "i32"));
    s.push_str("}\n\npub mod load {\n");
    for (n, st) in by_code(&sdk.load.status) {
        let _ = writeln!(s, "    pub const {n}: i32 = {};", st.code);
    }
    s.push_str("}\n");
    s
}

/// One `code: (name, text),` line of a Python status table (expanded when it is wider than `PY_WIDTH`).
fn py_status(s: &mut String, name: &str, st: &Status) {
    let one = format!("    {}: ({name:?}, {:?}),", st.code, st.text);
    if one.chars().count() <= PY_WIDTH {
        s.push_str(&one);
        s.push('\n');
    } else {
        let _ = writeln!(
            s,
            "    {}: (\n        {name:?},\n        {:?},\n    ),",
            st.code, st.text
        );
    }
}

/// `tools/device/dkproto.py`: the protocol numbers and the status texts.
fn python_proto(sdk: &Sdk) -> String {
    let p = &sdk.protocol;
    let mut s = format!("# {HEADER}\n\n");
    let _ = writeln!(s, "VERSION = {}\n", p.version);
    s.push_str("CMD: dict[str, int] = {\n");
    for (n, v) in by_value(&p.commands) {
        let _ = writeln!(s, "    {n:?}: 0x{v:02X},");
    }
    s.push_str("}\n");
    for (n, v) in by_value(&p.commands) {
        let _ = writeln!(s, "CMD_{n} = 0x{v:02X}");
    }
    s.push_str("\nSTATUS: dict[int, tuple[str, str]] = {\n");
    for (n, st) in by_code(&p.status) {
        py_status(&mut s, n, st);
    }
    s.push_str("}\n\nLOAD_STATUS: dict[int, tuple[str, str]] = {\n");
    for (n, st) in by_code(&sdk.load.status) {
        py_status(&mut s, n, st);
    }
    s.push_str("}\n\nCAP: dict[str, int] = {\n");
    for (n, bit) in by_value(&p.caps) {
        let _ = writeln!(s, "    {n:?}: {bit},");
    }
    s.push_str("}\n");
    s
}

/// `packages/dkupload/src/gen_proto.rs`: the protocol numbers for the host client (statuses as `i8`, as `Status::code` has them).
fn rust_proto(sdk: &Sdk) -> String {
    let mut s = format!("// {HEADER}\n\n#![allow(dead_code)]\n\n");
    s.push_str(&proto_consts(sdk, "", "i8"));
    s
}

fn python(sdk: &Sdk) -> Result<String> {
    let mut s = format!("# {HEADER}\n\n");
    let rv = runtime_parts(sdk)?;
    let _ = writeln!(s, "RUNTIME_VERSION = ({}, {}, {})", rv.0, rv.1, rv.2);
    let _ = writeln!(s, "RUNTIME_PACKED = {:#08x}\n", pack_runtime(rv));
    s.push_str("KINDS: dict[int, tuple[str, tuple[str, str, str, str, str]]] = {\n");
    for k in &sdk.log.kind {
        let args: Vec<String> = k.args.iter().map(|a| format!("{a:?}")).collect();
        let args = args.join(", ");
        let one = format!("    {}: ({:?}, ({args})),", k.id, k.name);
        if one.chars().count() <= PY_WIDTH {
            s.push_str(&one);
            s.push('\n');
        } else {
            let _ = writeln!(
                s,
                "    {}: (\n        {:?},\n        ({args}),\n    ),",
                k.id, k.name
            );
        }
    }
    s.push_str("}\n");
    let g: Vec<String> = guards(sdk)?
        .iter()
        .map(|(id, n)| format!("{id}: {n:?}"))
        .collect();
    let one = format!("GUARD_KINDS: dict[int, str] = {{{}}}", g.join(", "));
    if one.chars().count() <= PY_WIDTH {
        let _ = writeln!(s, "{one}");
    } else {
        s.push_str("GUARD_KINDS: dict[int, str] = {\n");
        for e in &g {
            let _ = writeln!(s, "    {e},");
        }
        s.push_str("}\n");
    }
    let l = &sdk.log;
    for (n, v) in [
        ("F_ERROR", l.f_error),
        ("LEVEL_SHIFT", l.level_shift),
        ("LEVEL_MASK", l.level_mask),
        ("SOURCE_SHIFT", l.source_shift),
        ("SOURCE_MASK", l.source_mask),
    ] {
        let _ = writeln!(s, "{n} = {v}");
    }
    let levels: Vec<String> = LEVELS.iter().map(|n| format!("{n:?}")).collect();
    let _ = writeln!(s, "LEVELS = ({})", levels.join(", "));
    let c = &sdk.contract;
    let _ = writeln!(
        s,
        "CONTRACT = {{\"api\": ({}, {}), \"machine\": ({}, {}), \"fx\": ({}, {}), \"service\": ({}, {})}}",
        c.api[0],
        c.api[1],
        c.machine[0],
        c.machine[1],
        c.fx[0],
        c.fx[1],
        c.service[0],
        c.service[1]
    );
    Ok(s)
}

/// `sdk/dk_machine.inc`: `#define` lines, decimal values (the assembler upper-cases macro text, which breaks `0x` literals).
fn machine_inc(sdk: &Sdk) -> String {
    let m = &sdk.machine;
    let mut s = format!(
        "// {HEADER}\n// Decimal values: the assembler upper-cases macro text, which breaks `0x` literals after `+`.\n// The C view is sdk/dk_machine.h.\n"
    );
    for c in &m.consts {
        let _ = writeln!(s, "#define {} {}", c.name, c.value);
    }
    for (prefix, fields) in [("IN", &m.voice_in), ("DESC", &m.desc)] {
        for (i, f) in fields.iter().enumerate() {
            let _ = writeln!(s, "#define DK_{prefix}_{} {}", f.to_uppercase(), i * 4);
        }
        let _ = writeln!(s, "#define DK_{prefix}_BYTES {}", fields.len() * 4);
        for (i, f) in fields.iter().enumerate() {
            let _ = writeln!(s, "#define DK_{prefix}_W_{} {i}", f.to_uppercase());
        }
        let _ = writeln!(s, "#define DK_{prefix}_WORDS {}", fields.len());
    }
    s
}

/// `sdk/dk_fx.inc`: the same form as `dk_machine.inc` (`DK_FX_IN_*`, `DK_FX_DESC_*`).
fn fx_inc(sdk: &Sdk) -> String {
    let m = &sdk.fx;
    let mut s = format!(
        "// {HEADER}\n// Decimal values: the assembler upper-cases macro text, which breaks `0x` literals after `+`.\n// The C view is sdk/dk_fx.h. Do not include it together with dk_machine.inc (DK_BLOCK is in both).\n"
    );
    for c in &m.consts {
        let _ = writeln!(s, "#define {} {}", c.name, c.value);
    }
    for (prefix, fields) in [("IN", &m.fx_in), ("DESC", &m.desc)] {
        for (i, f) in fields.iter().enumerate() {
            let _ = writeln!(s, "#define DK_FX_{prefix}_{} {}", f.to_uppercase(), i * 4);
        }
        let _ = writeln!(s, "#define DK_FX_{prefix}_BYTES {}", fields.len() * 4);
        for (i, f) in fields.iter().enumerate() {
            let _ = writeln!(s, "#define DK_FX_{prefix}_W_{} {i}", f.to_uppercase());
        }
        let _ = writeln!(s, "#define DK_FX_{prefix}_WORDS {}", fields.len());
    }
    s
}

/// The outputs from the text of `sdk/sdk.toml`: (path relative to the repository root, text).
pub fn render(text: &str) -> Result<Vec<(String, String)>> {
    let sdk = parse(text)?;
    Ok(vec![
        (RUST_OUT.to_string(), rust(&sdk)),
        (PY_OUT.to_string(), python(&sdk)?),
        (INC_OUT.to_string(), machine_inc(&sdk)),
        (FX_INC_OUT.to_string(), fx_inc(&sdk)),
        (PROTO_PY_OUT.to_string(), python_proto(&sdk)),
        (PROTO_RS_OUT.to_string(), rust_proto(&sdk)),
    ])
}

/// The outputs, reading `sdk/sdk.toml` under the repository root.
pub fn generate(root: &std::path::Path) -> Result<Vec<(String, String)>> {
    let path = root.join(SOURCE);
    let text = std::fs::read_to_string(&path).map_err(|e| err!("{}: {e}", path.display()))?;
    render(&text)
}
