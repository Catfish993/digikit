//! The C ABI of the digikit runtime (`modules/core/runtime/abi.toml`): the structs, constants and exported functions that the runtime, the DIGIKIT
//! menu, `core/ui` and other callers share. `patchkit gen` writes the C header `modules/core/runtime/include/dkrt.h`, the Rust definitions of the
//! `dkrt-sdk` crate (`gen_abi.rs`) and a check of the runtime's functions against their types (`gen_abi_check.rs`); `gen --check` keeps them current.
//!
//! The result codes and the CAPACITY kinds are in `sdk/sdk.toml` and are repeated in the C header only. The struct layout is checked here
//! (no padding, so ColdFire gcc and a host agree) and again by the generated size and offset assertions of both languages.

use crate::error::*;
use crate::sdkgen::{AbiInputs, Sig, Ty, c_args, c_decl, is_ident, parse_fn, rust_fn};
use serde::Deserialize;
use std::collections::BTreeMap;
use std::fmt::Write;

/// The spec, relative to the repository root.
pub const SOURCE: &str = "modules/core/runtime/abi.toml";
/// The generated C header, relative to the repository root.
pub const C_OUT: &str = "modules/core/runtime/include/dkrt.h";
/// The generated Rust definitions (module `gen_abi` of `dkrt-sdk`), relative to the repository root.
pub const RUST_OUT: &str = "modules/core/runtime/sdk/src/gen_abi.rs";
/// The generated signature check of the runtime crate, relative to the repository root.
pub const CHECK_OUT: &str = "modules/core/runtime/src/rs/src/gen_abi_check.rs";

const HEADER: &str =
    "Generated by `patchkit gen` from modules/core/runtime/abi.toml and sdk/sdk.toml. Do not edit.";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Abi {
    r#const: Vec<ConstToml>,
    r#struct: Vec<StructToml>,
    r#fn: Vec<FnToml>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct ConstToml {
    name: String,
    /// `u32`, `i32` or `usize` (an array length).
    r#type: String,
    value: i64,
    doc: String,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct StructToml {
    name: String,
    doc: String,
    #[serde(default)]
    derive: Vec<String>,
    /// `"<type> <name>[N][M] // doc"`.
    fields: Vec<String>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct FnToml {
    name: String,
    /// `<ret> <name>(<type> <name>, ...)`.
    sig: String,
    doc: String,
    /// The Rust module of the runtime crate that defines the function; empty: the crate root.
    #[serde(default)]
    at: String,
}

/// A field with its place.
struct Field {
    name: String,
    /// `u8`, `u16`, `u32`, `i32` or an earlier struct.
    base: String,
    /// The texts of the array lengths (a number or a const name), outermost first.
    dims: Vec<String>,
    off: usize,
    doc: String,
}

struct Layout {
    name: String,
    doc: String,
    derive: Vec<String>,
    fields: Vec<Field>,
    size: usize,
}

/// (size, alignment) of a scalar type.
fn scalar(t: &str) -> Option<(usize, usize)> {
    match t {
        "u8" => Some((1, 1)),
        "u16" => Some((2, 2)),
        "u32" | "i32" => Some((4, 4)),
        _ => None,
    }
}

fn c_scalar(t: &str) -> String {
    match t {
        "u8" => "uint8_t".to_string(),
        "u16" => "uint16_t".to_string(),
        "u32" => "uint32_t".to_string(),
        "i32" => "int32_t".to_string(),
        s => s.to_string(),
    }
}

/// The structs with their layout, checked.
fn layouts(abi: &Abi, sizes: &BTreeMap<String, usize>) -> Result<Vec<Layout>> {
    let mut out: Vec<Layout> = Vec::new();
    // (size, alignment) per struct
    let mut known: BTreeMap<String, (usize, usize)> = BTreeMap::new();
    for s in &abi.r#struct {
        let what = format!("[[struct]] {}", s.name);
        if !is_ident(&s.name) || known.contains_key(&s.name) {
            return Err(err!("{SOURCE}: {what}: bad name or name twice"));
        }
        if s.doc.is_empty() || s.doc.contains("*/") {
            return Err(err!("{SOURCE}: {what}: needs a doc without a comment end"));
        }
        let mut fields: Vec<Field> = Vec::new();
        let mut off = 0usize;
        let mut align = 1usize;
        for entry in &s.fields {
            let (decl, doc) = entry.split_once(" // ").unwrap_or((entry, ""));
            if doc.contains("*/") {
                return Err(err!(
                    "{SOURCE}: {what}: {entry:?}: the doc has a comment end"
                ));
            }
            let Some((ty, rest)) = decl.trim().split_once(char::is_whitespace) else {
                return Err(err!("{SOURCE}: {what}: {entry:?} needs a type and a name"));
            };
            let rest = rest.trim();
            let (name, mut tail) = match rest.find('[') {
                Some(i) => (&rest[..i], &rest[i..]),
                None => (rest, ""),
            };
            if !is_ident(name) || fields.iter().any(|f| f.name == name) {
                return Err(err!(
                    "{SOURCE}: {what}: field {name:?}: bad name or name twice"
                ));
            }
            let mut dims = Vec::new();
            let mut count = 1usize;
            while !tail.is_empty() {
                let inner = tail
                    .strip_prefix('[')
                    .and_then(|t| t.split_once(']'))
                    .ok_or_else(|| err!("{SOURCE}: {what}: {entry:?}: bad array length"))?;
                let text = inner.0.trim();
                let n = match text.parse::<usize>() {
                    Ok(n) => n,
                    Err(_) => *sizes.get(text).ok_or_else(|| {
                        err!("{SOURCE}: {what}: field {name}: {text:?} is not a number or a usize const")
                    })?,
                };
                if n == 0 {
                    return Err(err!("{SOURCE}: {what}: field {name}: array length is 0"));
                }
                count *= n;
                dims.push(text.to_string());
                tail = inner.1.trim();
            }
            let (esize, ealign) = match scalar(ty) {
                Some(v) => v,
                None => *known
                    .get(ty)
                    .ok_or_else(|| err!("{SOURCE}: {what}: field {name}: unknown type {ty:?}"))?,
            };
            if off % ealign != 0 {
                return Err(err!(
                    "{SOURCE}: {what}: field {name} at {off} needs padding (alignment {ealign})"
                ));
            }
            align = align.max(ealign);
            fields.push(Field {
                name: name.to_string(),
                base: ty.to_string(),
                dims,
                off,
                doc: doc.to_string(),
            });
            off += esize * count;
        }
        if fields.is_empty() {
            return Err(err!("{SOURCE}: {what}: has no fields"));
        }
        if off % 4 != 0 {
            return Err(err!(
                "{SOURCE}: {what}: size {off} is not a multiple of 4 (padding)"
            ));
        }
        for d in &s.derive {
            if d != "Clone" && d != "Copy" {
                return Err(err!("{SOURCE}: {what}: derive {d:?} is Clone or Copy"));
            }
        }
        known.insert(s.name.clone(), (off, align));
        out.push(Layout {
            name: s.name.clone(),
            doc: s.doc.clone(),
            derive: s.derive.clone(),
            fields,
            size: off,
        });
    }
    Ok(out)
}

/// The array lengths a field can name: the `usize` consts of the file and `SEL_MAX`.
fn size_names(abi: &Abi, inputs: &AbiInputs) -> Result<BTreeMap<String, usize>> {
    let mut sizes = BTreeMap::new();
    sizes.insert("SEL_MAX".to_string(), inputs.sel_max as usize);
    let mut seen: Vec<&str> = Vec::new();
    for c in &abi.r#const {
        let what = format!("[[const]] {}", c.name);
        if !is_ident(&c.name) || c.name == "SEL_MAX" || seen.contains(&c.name.as_str()) {
            return Err(err!("{SOURCE}: {what}: bad name or name twice"));
        }
        seen.push(&c.name);
        if c.doc.is_empty() || c.doc.contains("*/") {
            return Err(err!("{SOURCE}: {what}: needs a doc without a comment end"));
        }
        let ok = match c.r#type.as_str() {
            "u32" | "usize" => (0..=i64::from(u32::MAX)).contains(&c.value),
            "i32" => (i64::from(i32::MIN)..=i64::from(i32::MAX)).contains(&c.value),
            t => return Err(err!("{SOURCE}: {what}: unknown type {t:?}")),
        };
        if !ok {
            return Err(err!(
                "{SOURCE}: {what}: value {} does not fit {}",
                c.value,
                c.r#type
            ));
        }
        if c.r#type == "usize" {
            sizes.insert(c.name.clone(), c.value as usize);
        }
    }
    Ok(sizes)
}

/// The exported functions with their signatures, checked.
fn functions(abi: &Abi) -> Result<Vec<(&FnToml, Sig)>> {
    let mut extra: Vec<&str> = abi.r#struct.iter().map(|s| s.name.as_str()).collect();
    extra.push("usize");
    let none = BTreeMap::new();
    let mut out: Vec<(&FnToml, Sig)> = Vec::new();
    for f in &abi.r#fn {
        let what = format!("[[fn]] {}", f.name);
        let (name, sig) = parse_fn(&what, &f.sig, &none, &extra)?;
        if name.as_deref() != Some(f.name.as_str()) || out.iter().any(|(o, _)| o.name == f.name) {
            return Err(err!(
                "{SOURCE}: {what}: the signature names another function, or the name is twice"
            ));
        }
        if f.doc.is_empty() || f.doc.contains("*/") {
            return Err(err!("{SOURCE}: {what}: needs a doc without a comment end"));
        }
        if !f.at.split("::").all(|p| p.is_empty() || is_ident(p)) {
            return Err(err!("{SOURCE}: {what}: bad module path {:?}", f.at));
        }
        out.push((f, sig));
    }
    Ok(out)
}

/// A const as Rust text: a magic number in hex, the rest in decimal.
fn const_value(c: &ConstToml) -> String {
    if c.name.ends_with("_MAGIC") {
        format!("{:#010x}", c.value)
    } else {
        c.value.to_string()
    }
}

/// Rust text of a field's type: the base wrapped in an array per length.
fn rust_field_ty(f: &Field) -> String {
    let mut t = f.base.clone();
    for d in f.dims.iter().rev() {
        t = format!("[{t}; {d}]");
    }
    t
}

fn rust(abi: &Abi, lays: &[Layout], fns: &[(&FnToml, Sig)], inputs: &AbiInputs) -> String {
    let mut s = format!("// {HEADER}\n\nuse core::mem::{{offset_of, size_of}};\n\n");
    for c in &abi.r#const {
        let _ = writeln!(s, "/// {}", c.doc);
        let ty = if c.r#type == "usize" {
            "usize"
        } else {
            c.r#type.as_str()
        };
        let _ = writeln!(s, "pub const {}: {ty} = {};", c.name, const_value(c));
    }
    let _ = writeln!(
        s,
        "/// Paths of the selection (`[limits.max] modules` of sdk/sdk.toml).\npub const SEL_MAX: usize = {};",
        inputs.sel_max
    );
    for l in lays {
        let _ = writeln!(s, "\n/// {}\n#[repr(C)]", l.doc);
        if !l.derive.is_empty() {
            let _ = writeln!(s, "#[derive({})]", l.derive.join(", "));
        }
        let _ = writeln!(s, "pub struct {} {{", l.name);
        for f in &l.fields {
            if !f.doc.is_empty() {
                let _ = writeln!(s, "    /// {}", f.doc);
            }
            let _ = writeln!(s, "    pub {}: {},", f.name, rust_field_ty(f));
        }
        s.push_str("}\n");
        let _ = writeln!(
            s,
            "const _: () = assert!(size_of::<{}>() == {}, \"{} size\");",
            l.name, l.size, l.name
        );
        for f in &l.fields {
            let _ = writeln!(
                s,
                "const _: () = assert!(offset_of!({}, {}) == {}, \"{}.{}\");",
                l.name, f.name, f.off, l.name, f.name
            );
        }
    }
    s.push_str("\n/// The type of each export. The runtime crate checks its functions against them (`src/rs/src/gen_abi_check.rs`).\n#[allow(non_camel_case_types)]\npub mod sig {\n    use super::*;\n");
    for (f, sig) in fns {
        let _ = writeln!(s, "\n    /// {}", f.doc);
        let _ = writeln!(s, "    pub type {} = {};", f.name, rust_fn(sig));
    }
    s.push_str("}\n");
    s
}

/// The signature with C types: `usize` is a `uintptr_t`.
fn c_sig(sig: &Sig) -> Sig {
    let fix = |t: &Ty| {
        let mut t = t.clone();
        if t.base == "usize" {
            t.base = "uintptr_t".to_string();
        }
        t
    };
    Sig {
        ret: fix(&sig.ret),
        args: sig.args.iter().map(|(t, n)| (fix(t), n.clone())).collect(),
    }
}

/// A line comment text that cannot end the comment.
fn c_text(t: &str) -> String {
    t.replace("*/", "* /")
}

fn c_header(abi: &Abi, lays: &[Layout], fns: &[(&FnToml, Sig)], inputs: &AbiInputs) -> String {
    let mut s = format!(
        "/* {HEADER} */\n/* modules/core/runtime/include/dkrt.h -- the C ABI of the digikit runtime (core/runtime): the exported functions, the structs they fill and the constants.\n   Every call is a gcc m68k cdecl call (arguments on the stack, result in d0); there are no small-struct results. Task context only. */\n#ifndef DKRT_H\n#define DKRT_H\n\n#include <stddef.h>\n#include <stdint.h>\n\n"
    );
    for c in &abi.r#const {
        let _ = writeln!(s, "/* {} */", c_text(&c.doc));
        let v = if c.name.ends_with("_MAGIC") {
            format!("{:#010x}u", c.value)
        } else if c.value < 0 {
            format!("({})", c.value)
        } else {
            c.value.to_string()
        };
        let _ = writeln!(s, "#define DKRT_{} {v}", c.name);
    }
    let _ = writeln!(
        s,
        "/* Paths of the selection ([limits.max] modules of sdk/sdk.toml). */\n#define DKRT_SEL_MAX {}",
        inputs.sel_max
    );
    s.push_str("\n/* Result codes (negative = error), from [load.status] of sdk/sdk.toml. Additive: a code is never renumbered. */\n");
    for (n, code, text) in &inputs.codes {
        let d = format!("#define DKRT_{n} ({code})");
        let _ = writeln!(s, "{d:<40} /* {} */", c_text(text));
    }
    s.push_str("\n/* CAPACITY kinds (DkrtCap.kind), from [capacity.kinds] of sdk/sdk.toml. */\n");
    for (n, k) in &inputs.kinds {
        let _ = writeln!(s, "#define DKRT_CAPK_{n} {k}");
    }
    s.push('\n');
    for l in lays {
        let _ = writeln!(s, "/* {} */\ntypedef struct {} {{", c_text(&l.doc), l.name);
        for f in &l.fields {
            let mut dims = String::new();
            for d in &f.dims {
                if d.parse::<usize>().is_ok() {
                    let _ = write!(dims, "[{d}]");
                } else {
                    let _ = write!(dims, "[DKRT_{d}]");
                }
            }
            let d = format!("    {} {}{dims};", c_scalar(&f.base), f.name);
            if f.doc.is_empty() {
                let _ = writeln!(s, "{d}");
            } else {
                let _ = writeln!(s, "{d:<48} /* {} */", c_text(&f.doc));
            }
        }
        let _ = writeln!(s, "}} {};\n", l.name);
    }
    for l in lays {
        let _ = writeln!(
            s,
            "_Static_assert(sizeof({}) == {}, \"{} size\");",
            l.name, l.size, l.name
        );
        for f in &l.fields {
            let _ = writeln!(
                s,
                "_Static_assert(offsetof({}, {}) == {}, \"{}.{}\");",
                l.name, f.name, f.off, l.name, f.name
            );
        }
    }
    s.push_str("\n/* The exports of the runtime. */\n");
    for (f, sig) in fns {
        let sig = c_sig(sig);
        let _ = writeln!(s, "\n/* {} */", c_text(&f.doc));
        let _ = writeln!(
            s,
            "{};",
            c_decl(&sig.ret, &format!("{}({})", f.name, c_args(&sig)))
        );
    }
    s.push_str("\n#endif /* DKRT_H */\n");
    s
}

fn check(fns: &[(&FnToml, Sig)]) -> String {
    let mut s = format!(
        "// {HEADER}\n\n// The runtime's exports have the types of `abi.toml`: a changed signature fails the build here.\nuse dkrt_sdk::gen_abi::sig;\n\n"
    );
    for (f, _) in fns {
        let path = if f.at.is_empty() {
            format!("crate::{}", f.name)
        } else {
            format!("crate::{}::{}", f.at, f.name)
        };
        let _ = writeln!(s, "const _: sig::{} = {path};", f.name);
    }
    s
}

/// The outputs from the text of `abi.toml` and what it takes from `sdk/sdk.toml`: (path relative to the repository root, text).
pub(crate) fn render(text: &str, inputs: &AbiInputs) -> Result<Vec<(String, String)>> {
    let abi: Abi = toml::from_str(text).map_err(|e| err!("{SOURCE}: {e}"))?;
    let sizes = size_names(&abi, inputs)?;
    let lays = layouts(&abi, &sizes)?;
    let fns = functions(&abi)?;
    Ok(vec![
        (C_OUT.to_string(), c_header(&abi, &lays, &fns, inputs)),
        (RUST_OUT.to_string(), rust(&abi, &lays, &fns, inputs)),
        (CHECK_OUT.to_string(), check(&fns)),
    ])
}

/// `render` from the texts of `abi.toml` and `sdk/sdk.toml` (for the tests).
pub fn render_with(abi_text: &str, sdk_text: &str) -> Result<Vec<(String, String)>> {
    render(abi_text, &crate::sdkgen::abi_inputs(sdk_text)?)
}
