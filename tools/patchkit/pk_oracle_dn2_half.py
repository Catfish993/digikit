#!/usr/bin/env python3
"""Generate the DN2 master-half oracle module from tools/patchkit/dsp_patches/dn2-1.12-master-half.patch.

    uv run python -m tools.patchkit.pk_oracle_dn2_half

Writes out/modules/oracle/dn2-master-half/module.toml: one `write` at the Q31 converter anchor replacing the
instruction word `R2 = 0x1f` by `R2 = 0x1e`. The new word is a firmware instruction, so the module is
generated (never committed); patchkit finds it through --modules-dir / PATCHKIT_MODULES (default out/modules).
"""

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PATCH = ROOT / "tools" / "patchkit" / "dsp_patches" / "dn2-1.12-master-half.patch"
OUT = ROOT / "out" / "modules" / "oracle" / "dn2-master-half" / "module.toml"
CONVERTER_PC = (
    0x1C9D3F  # entry of the Q31 converter (anchor dsp.master.fn.q31_converter)
)


def stream_hex(words: str) -> str:
    """Instruction-order hex words -> boot-stream order (each 16-bit parcel little endian)."""
    return "".join(
        words[i + 2 : i + 4] + words[i : i + 2] for i in range(0, len(words), 4)
    )


def main() -> int:
    m = re.search(r"^PM\s+(\w+)\s+(\w+)\s+was\s+(\w+)", PATCH.read_text(), re.M)
    if not m:
        raise SystemExit("no PM line in the patch")
    pc, new, old = int(m.group(1), 16), m.group(2), m.group(3)
    offset = (pc - CONVERTER_PC) * 2
    text = f"""# Generated by tools/patchkit/pk_oracle_dn2_half.py: do not edit, do not commit (holds a firmware instruction word).
[module]
id = "oracle/dn2-master-half"
version = "0.1.0"
name = "DN2 master half (oracle)"
category = "oracle"
type = "raw"
author = "digikit"
status = "pinned"
summary = "One write: the master Q31 scale 31 -> 30 (-6 dB). Must equal tools/patchkit/dsp_patches/dn2-1.12-master-half.patch applied by tools/patchkit/dsp_patch.py"
ports = ["dn2-1.12"]

[targets]
"dn2-1.12" = "tested"

[[op]]
op = "write"
anchor = "dsp.master.fn.q31_converter"
offset = {offset}
hex = "{stream_hex(new)}"
expect_sha256 = "{hashlib.sha256(bytes.fromhex(stream_hex(old))).hexdigest()}"

[[claim]]
resource = "dsp.master.scale"
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"{OUT}: write at +{offset}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
