#!/usr/bin/env python3
"""Convert the machinebuild plan for XSLICE (Digitakt II 1.16) into the pinned raw-writes module.

    uv run python -m tools.patchkit.pk_oracle_xslice [--check]

Runs tools/patchkit/machinebuild.py's planner (`plan_and_verify`) for `--machine XSLICE:XSL:6:7 --fields
0xf8,0xf9,0xfa,0xfb,0xfc,0xfd,0,0xfe,0x0a` against the 1.16 MAIN OS and writes
out/modules/oracle/xslice-dt2-1-16/module.toml (firmware-derived, not committed): one `write` per planned write, addressed from the `cf.main`
anchor (the whole MAIN OS image, base 0x40000400), each pinned by the sha256 of the bytes it replaces.
Patched section 3 must hash to cdbd7726...ecb86a (docs/findings/02-machines-and-parameters.md, "XSLICE").
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from dataclasses import replace
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

from tools.patchkit import machinebuild  # noqa: E402
from tools.patchkit import machinepatch as mp  # noqa: E402

FIELDS = (0xF8, 0xF9, 0xFA, 0xFB, 0xFC, 0xFD, 0, 0xFE, 0x0A)
MAIN_BASE = 0x40000400
# Not under modules/: the new bytes include words copied from the 1.16 image, so the file is firmware-derived
# and never committed. patchkit finds it through --modules-dir / PATCHKIT_MODULES (default root: out/modules).
OUT = ROOT / "out" / "modules" / "oracle" / "xslice-dt2-1-16" / "module.toml"
PINNED_SECTION3 = "cdbd7726"  # prefix; the full hash is checked by the Rust oracle test


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    from tools.patchkit import port_resolve

    secs = port_resolve.sections_of(ROOT / "Digitakt_II_OS1.16.syx")
    import tempfile

    with tempfile.NamedTemporaryFile(suffix=".bin") as f:
        f.write(secs[3])
        f.flush()
        spec = replace(mp.spec_from_arg("XSLICE:XSL:6:7"), fields=FIELDS)
        writes, patched = machinebuild.plan_and_verify(
            f.name, machinebuild.PROFILE_BY_NAME["dt2-1.16"], spec, mp.PARTS
        )
    digest = hashlib.sha256(patched).hexdigest()
    if not digest.startswith(PINNED_SECTION3):
        raise SystemExit(
            f"patched section 3 is {digest}, expected {PINNED_SECTION3}..."
        )
    lines = [
        "# Generated by tools/patchkit/pk_oracle_xslice.py from the machinebuild plan: do not edit by hand.",
        "# XSLICE, an eighth machine on Digitakt II 1.16 (docs/findings/02-machines-and-parameters.md).",
        f"# Patched section 3 sha256 {digest}.",
        "",
        "[module]",
        'id = "oracle/xslice-dt2-1-16"',
        'version = "0.1.0"',
        'name = "XSLICE (oracle)"',
        'category = "oracle"',
        'status = "pinned"',
        'summary = "Raw writes of the machinebuild plan for XSLICE on DT2 1.16; patched section 3 is pinned"',
        'ports = ["dt2-1.16"]',
        "",
        "[targets]",
        '"dt2-1.16" = "tested"',
    ]
    # The plan's writes can overlap (later ones refine earlier ones); a module's writes may not. Merge the
    # written intervals, and emit each as the final bytes over the original bytes.
    spans: list[list[int]] = []
    for addr, _old, new in sorted(writes, key=lambda w: w[0]):
        if spans and addr <= spans[-1][1]:
            spans[-1][1] = max(spans[-1][1], addr + len(new))
        else:
            spans.append([addr, addr + len(new)])
    for lo, hi in spans:
        old = secs[3][lo - MAIN_BASE : hi - MAIN_BASE]
        new = patched[lo - MAIN_BASE : hi - MAIN_BASE]
        lines += [
            "",
            "[[op]]",
            'op = "write"',
            'anchor = "cf.main"',
            f"offset = {lo - MAIN_BASE}",
            f'hex = "{new.hex()}"',
            f'expect_sha256 = "{hashlib.sha256(old).hexdigest()}"',
        ]
    text = "\n".join(lines) + "\n"
    if a.check:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(
        f"{OUT}: {len(writes)} planned writes in {len(spans)} spans, section 3 sha256 {digest}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
